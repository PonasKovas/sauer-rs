pub const COLOR_ESCAPE: u8 = 0x0C;

macro_rules! make_tables {
    ( $( $cube:literal = $uni:literal ),+ ) => {
        pub fn cube2uni(cube: u8) -> char {
            let uni = match cube {
                $(
                    $cube => $uni,
                )+
            };

            core::char::from_u32(uni).unwrap()
        }
        pub fn uni2cube(uni: char) -> Option<u8> {
            match uni as u32 {
                $(
                    $uni => Some($cube),
                )+
                _ => None,
            }
        }
    };
}

