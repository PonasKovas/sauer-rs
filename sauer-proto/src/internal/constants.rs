/// Declares every message id once, plus `msg_id_to_name` for logs and errors.
macro_rules! msg_ids {
    ($($name:ident = $val:literal,)*) => {
        $(pub const $name: i32 = $val;)*

        /// The engine name of a message id, or `"<unknown>"`.
        pub(crate) fn msg_id_to_name(id: i32) -> &'static str {
            match id {
                $($name => stringify!($name),)*
                _ => "<unknown>",
            }
        }
    };
}

